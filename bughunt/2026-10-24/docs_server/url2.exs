alias ImagePipe.URL, as: U
p = fn l, f -> r = try do f.() rescue e -> {:raised, e.__struct__, Exception.message(e)} end; IO.puts("#{l}: #{inspect(r, limit: 12, printable_limit: 300, pretty: false) |> String.slice(0, 600)}") end
key = String.duplicate("ab", 32); ek = String.duplicate("cd", 32)
config = U.config(keys: [key], base_url: "https://cdn.example.com/images")
builder = U.new(config) |> U.group(resize: [width: 400, height: 300, fit: :cover], anchor: :smart) |> U.output(format: :webp, quality: 82)
p.("mod validate", fn -> U.validate(builder) end)
p.("mod url", fn -> U.url!(builder, "images/cat.jpg") end)
b2 = U.new() |> U.group(resize: [width: 300, fit: :fill])
p.("mistake validate", fn -> U.validate(b2) end)
