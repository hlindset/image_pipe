p = fn l, f -> r = try do f.() rescue e -> {:raised, e.__struct__, Exception.message(e)} end; IO.puts("#{l}: #{inspect(r, limit: 8, printable_limit: 200) |> String.slice(0, 400)}") end
strip = fn {:ok, r} -> {:ok, r.format, r.width}; o -> o end
p.("missing file", fn -> ImagePipe.run(c, b, {:file, d <> "/nope.jpg"}) end)
