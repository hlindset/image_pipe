p.("detector required", fn -> ImagePipe.run(ImagePipe.config(detector_required: true), ImagePipe.URL.new() |> ImagePipe.URL.group(resize: [width: 40, height: 40, fit: :cover], gravity: [type: :object, classes: ["face"]]) , {:file, photo}) end)
