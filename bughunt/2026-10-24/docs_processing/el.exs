IO.inspect(ImagePipe.URL.url!(sq, "photo.jpg"), label: "E sq url")
fill = ImagePipe.URL.new() |> ImagePipe.URL.group(resize: [width: 300, height: 300, fit: :fill])
IO.inspect(ImagePipe.run(config, fill, {:file, photo}), label: "E fill")
sw = ImagePipe.URL.output(sq, format: :webp)
IO.inspect(ImagePipe.URL.url!(sw, "photo.jpg"), label: "E sw url")
{:ok, res} = ImagePipe.run(config, sw, {:file, photo})
IO.inspect({res.format, res.width, res.height}, label: "E sw")
