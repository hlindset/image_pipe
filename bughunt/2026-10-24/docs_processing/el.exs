config = ImagePipe.config()
IO.inspect(config, label: "E cfg")
thumb = ImagePipe.URL.new() |> ImagePipe.URL.group(resize: [width: 400])
IO.inspect(ImagePipe.URL.url!(thumb, "photo.jpg"), label: "E url")
{:ok, res} = ImagePipe.run(config, thumb, {:file, photo})
IO.inspect({res.format, res.width, res.height, res.content_type, res.terminal}, label: "E run")
