alias Vix.Vips.{Operation, MutableImage}
alias Vix.Vips.Image, as: VI
out = Path.join(System.get_env("F"), "inputs")
File.mkdir_p!(out)
base = Image.new!(96, 64, color: [200, 30, 40]) |> Image.Draw.rect!(48, 0, 48, 64, color: [20, 160, 220])
{:ok, cmyk_prof} = Operation.profile_load("cmyk")
{:ok, srgb_prof} = Operation.profile_load("srgb")
{:ok, grey_prof} = Operation.profile_load("sgrey")
{:ok, p3_prof} = Operation.profile_load("p3")
[cmyk_prof, srgb_prof, grey_prof, p3_prof] = Enum.map([cmyk_prof, srgb_prof, grey_prof, p3_prof], fn b -> if is_binary(b), do: b, else: VI.to_binary(b) end) |> then(&(&1))
IO.inspect(Enum.map([cmyk_prof, srgb_prof, grey_prof, p3_prof], &byte_size/1), label: "profiles")
File.write!(Path.join(out, "prof_cmyk.icc"), cmyk_prof)
File.write!(Path.join(out, "prof_grey.icc"), grey_prof)
setp = fn img, prof ->
  {:ok, i} = VI.mutate(img, fn m -> if prof == :none, do: MutableImage.remove(m, "icc-profile-data"), else: MutableImage.set(m, "icc-profile-data", :VipsBlob, prof) end)
  i
end
w = fn img, name, opts ->
  path = Path.join(out, name)
  r = cond do
    String.ends_with?(name, ".jxl") -> VI.write_to_file(img, path)
    String.ends_with?(name, ".heif") -> Operation.heifsave(img, path, compression: :VIPS_FOREIGN_HEIF_COMPRESSION_AV1)
    opts[:palette] -> Operation.pngsave(img, path, palette: true)
    true -> Image.write(img, path, opts)
  end
  case r do
    {:ok, _} -> IO.puts("ok #{name}")
    :ok -> IO.puts("ok #{name}")
    e -> IO.puts("FAIL #{name} #{inspect e}")
  end
end
