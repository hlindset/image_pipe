defmodule ImagePipeServer.Config.Reference do
  @moduledoc """
  Renders the configuration reference from the schemas the loader converts
  with, so it lists exactly the settings the server accepts.

  `mix image_pipe_server.gen.reference` writes it into
  `docs/server-configuration.md`, between the `reference:start` and
  `reference:end` comments.
  """

  alias ImagePipeServer.Config
  alias ImagePipeServer.Config.Sources

  @start "<!-- reference:start (generated by mix image_pipe_server.gen.reference) -->"
  @finish "<!-- reference:end -->"

  @intros [
    server:
      "The HTTP listener. `mount_path` is the path that image URLs start with, such as " <>
        "`/images`. It starts with `/` and holds only letters, digits, and `-._~` between " <>
        "its slashes. The server refuses to start with any other character. " <>
        "Times are in milliseconds. `read_timeout` closes connections " <>
        "that send nothing for that long, idle keep-alive connections included. " <>
        "With `auth_token`, requests other than the health checks, `/stats`, and `/metrics` " <>
        "must send " <>
        "`Authorization: Bearer <token>`. The token needs at least 32 characters. " <>
        "On shutdown, `/health/ready` answers `503` " <>
        "while the server keeps serving for `shutdown_delay`. Then in-flight requests " <>
        "get `shutdown_timeout` to finish. `health_port` serves the health checks on a " <>
        "separate listener, outside `max_connections`, at the address in `health_bind`, " <>
        "or else `bind`. See " <>
        "[health and shutdown](server-deployment.md#health-and-shutdown).",
    url:
      "How the server checks request URLs: the signing keys and the keys that decrypt " <>
        "`enc/` image paths. See [signing URLs and rotating keys](../../image_pipe/docs/signing-urls.md). " <>
        "Without `keys`, the server doesn't start unless `allow_unsigned = true`. That " <>
        "setting lets the server answer URLs without a signature, and the server logs a " <>
        "warning at startup. Set it only for a server that nothing outside a private " <>
        "network can reach.",
    sources: nil,
    cache:
